#requires -Version 7.0
param([switch]$ReadErrorsOnly, [switch]$TransportOnly, [switch]$PatchErrorsOnly, [switch]$FusionOnly, [switch]$CompatibilityOnly)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$runner = (Resolve-Path (Join-Path $PSScriptRoot '..\tools\Invoke-SdlcCapture.ps1')).Path
$fake = (Resolve-Path (Join-Path $PSScriptRoot 'fixtures\fake-copilot.ps1')).Path
$fixture = New-Item -ItemType Directory -Path (Join-Path ([IO.Path]::GetTempPath()) ("sdlc-capture-test-" + [guid]::NewGuid().ToString('N')))
$repository = Join-Path $fixture.FullName 'repository'
[void](New-Item -ItemType Directory -Path (Join-Path $repository '.github\agents') -Force)
$agentFile = Join-Path $repository '.github\agents\pilotRole_Product_Manager.agent.md'
'---', 'name: pilotRole_Product_Manager', '---', 'Fixture agent.' | Set-Content $agentFile
$promptFile = Join-Path $fixture.FullName 'prompt.txt'
$prompt = "Unicode: $([char]0x5FAE)$([char]0x4FE1)`nQuotes: `"value`" & `$variable; --resume"
$prompt | Set-Content $promptFile -NoNewline -Encoding utf8
$oldMode = $env:SDLC_CAPTURE_FIXTURE
$originalLocation = Get-Location
Import-Module (Join-Path $PSScriptRoot '..\tools\CapturedProcess.psm1') -Force

function Assert($Condition, $Message) {
    if (-not $Condition) { throw "ASSERTION FAILED: $Message" }
}

function Invoke-Fixture($RunName, $Expected, [switch]$Resume) {
    $output = Join-Path $fixture.FullName $RunName
    $arguments = @('-NoProfile', '-File', $runner, '-RepositoryPath', $repository,
        '-PromptFile', $promptFile, '-RunDirectory', $output, '-CliPath', $fake,
        '-AllowTool', 'url(https://example.invalid)', '-DenyTool', 'shell(git:*)',
        '-TimeoutSeconds', $(if ($env:SDLC_CAPTURE_FIXTURE -eq 'timeout') { '2' } else { '10' }))
    if ($Resume) { $arguments += '-Resume' }
    if ($env:SDLC_CAPTURE_FIXTURE -eq 'read_no_tools') { $arguments += '-NoTools' }
    if ($env:SDLC_CAPTURE_FIXTURE -like 'patch_*' -and $env:SDLC_CAPTURE_FIXTURE -ne 'patch_disabled') { $arguments += '-RecoverLocalPatchErrors' }
    & pwsh @arguments | Out-Host
    Assert ($LASTEXITCODE -eq $Expected) "$RunName exit $LASTEXITCODE, expected $Expected"
    return $output
}

try {
    Set-Location $repository
    & git init --quiet
    if ($LASTEXITCODE -ne 0) { throw 'Fixture git init failed.' }
    & git -c user.name=Fixture -c user.email=fixture@example.invalid -c commit.gpgsign=false commit --quiet --allow-empty -m "test: initialize capture fixture`n`nGenerated by Copilot`n`nCo-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>"
    if ($LASTEXITCODE -ne 0) { throw 'Fixture git commit failed.' }

    if ($CompatibilityOnly -or -not $PSBoundParameters.Count) {
        foreach ($mode in @('remote_modern', 'remote_legacy', 'remote_unknown', 'help_failure')) {
            $env:SDLC_CAPTURE_FIXTURE = $mode
            $output = Join-Path $fixture.FullName $mode
            & pwsh -NoProfile -File $runner -RepositoryPath $repository -PromptFile $promptFile -RunDirectory $output `
                -CliPath $fake -CopilotHome (Join-Path $fixture.FullName "$mode-home") -TimeoutSeconds 10 | Out-Host
            $code = $LASTEXITCODE
            $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
            $meta = Get-Content (Join-Path $turn 'turn.json') -Raw | ConvertFrom-Json -AsHashtable
            Assert (Test-Path (Join-Path $turn 'help.stdout')) 'CLI capability evidence must be saved.'
            if ($mode -in @('remote_unknown', 'help_failure')) {
                Assert ($code -ne 0 -and -not (Test-Path (Join-Path $turn 'events.stdout')) -and $meta.errors.Count -gt 0) 'Missing or failed capability discovery must block inference explicitly.'
            } else {
                Assert ($code -eq 0) "$mode capture must succeed."
                $arguments = $meta.command.arguments
                Assert ($arguments -contains '--disallow-temp-dir') 'Temp isolation must remain enabled.'
                if ($mode -eq 'remote_modern') {
                    Assert ($arguments -contains '--sync-session=off' -and $arguments -notcontains '--no-remote' -and
                        $arguments -notcontains '--no-remote-export') 'Modern CLI must disable sync without removed flags.'
                } else {
                    Assert ($arguments -contains '--no-remote' -and $arguments -contains '--no-remote-export' -and
                        $arguments -notcontains '--sync-session=off') 'Legacy CLI must retain supported remote-disable flags.'
                }
                Assert ($meta.cliIsolation.policy -eq 'help-detected-v1') 'Capability selection must be auditable.'
            }
        }
        $errors = $null
        $ast = [Management.Automation.Language.Parser]::ParseFile($runner, [ref]$null, [ref]$errors)
        Assert ($errors.Count -eq 0) 'Collector must parse.'
        $definition = $ast.Find({ param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Get-CliIsolationArguments' }, $false)
        . ([scriptblock]::Create($definition.Extent.Text))
        $rejected = $false
        try { Get-CliIsolationArguments "  --sync-session[=<on|off>]" | Out-Null } catch { $rejected = $true }
        Assert $rejected 'Missing temp protection must not silently weaken isolation.'
        $rejected = $false
        try { Get-CliIsolationArguments "  --disallow-temp-dir`nThe removed --no-remote and --no-remote-export options are unsupported." | Out-Null } catch { $rejected = $true }
        Assert $rejected 'Mentions of removed flags in prose are not supported options.'
        Write-Host 'PASS: CLI isolation capability discovery, modern/legacy arguments, fail-closed unknown/help failure and saved evidence.'
        if ($CompatibilityOnly) { return }
    }

    if ($FusionOnly -or -not $PSBoundParameters.Count) {
        $env:SDLC_CAPTURE_FIXTURE = 'fusion_routing'
        foreach ($selector in @('fusion', 'fusion:standard', 'fusion:high', 'fusion:max', 'auto', 'auto:hydrafusion', 'hydrafusion')) {
            $output = Join-Path $fixture.FullName ($selector.Replace(':', '-'))
            & pwsh -NoProfile -File $runner -RepositoryPath $repository -PromptFile $promptFile `
                -RunDirectory $output -CliPath $fake -Model $selector -TimeoutSeconds 10 | Out-Host
            Assert ($LASTEXITCODE -eq 0) "$selector capture failed."
            $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
            $meta = Get-Content (Join-Path $turn 'turn.json') -Raw | ConvertFrom-Json -AsHashtable
            $events = @(Get-Content (Join-Path $turn 'events.stdout') | ForEach-Object { $_ | ConvertFrom-Json -AsHashtable })
            $actualArgs = $events[0].data.arguments
            $runtime = Get-Content (Join-Path $turn 'runtime.json') -Raw | ConvertFrom-Json -AsHashtable
            Assert ($runtime.observedModels.Count -eq 2 -and 'fixture-model' -in $runtime.observedModels -and
                'fixture-usage-model' -in $runtime.observedModels) 'Selectors must not be reported as concrete models in events or usage metrics.'
            $tier = switch ($selector) {
                'fusion' { 'standard' }; 'fusion:standard' { 'standard' }
                'fusion:high' { 'high' }; 'fusion:max' { 'max' }
            }
            if ($tier) {
                $routing = @{ standard = 'balance'; high = 'hydrafusion'; max = 'hydrafusion-max' }[$tier]
                Assert ($meta.requestedFusionTier -eq $tier -and $meta.requestedAutoTier -eq $routing -and
                    $actualArgs[([Array]::IndexOf($actualArgs, '--model') + 1)] -eq 'auto' -and
                    $actualArgs[([Array]::IndexOf($actualArgs, '--auto-tier') + 1)] -eq $routing) "$selector exact CLI arguments mismatch."
                Assert (($actualArgs -contains '--experimental') -eq ($tier -ne 'standard')) "$selector experimental flag mismatch."
            }
        }
        $output = Join-Path $fixture.FullName 'conflicting-tier'
        & pwsh -NoProfile -File $runner -RepositoryPath $repository -PromptFile $promptFile `
            -RunDirectory $output -CliPath $fake -Model 'fusion:high' -AutoTier 'balance' -TimeoutSeconds 10 | Out-Host
        Assert ($LASTEXITCODE -ne 0) 'Conflicting explicit routing must fail, not silently select Standard.'
        Assert (-not (Get-ChildItem $output -Recurse -Filter 'events.stdout')) 'Conflicting routing must be rejected before inference.'
        Write-Host 'PASS: Fusion Standard/High/Max exact arguments, legacy selectors and conflicting routing rejection.'
        if ($FusionOnly) { return }
    }

    if ($TransportOnly -or -not $PSBoundParameters.Count) {
        $shortPrompt = $prompt
        $prompt = ConvertTo-Json -InputObject @{ oracle = @{ initial = $shortPrompt }; dialogue = @((1..1500) | ForEach-Object { @{ role = 'user'; content = "$shortPrompt`r`nRound $_" } }) } -Depth 8
        Assert ($prompt.Length -gt 65536) 'Transport fixture exceeds Windows command-line limit'
        $prompt | Set-Content $promptFile -Encoding utf8 -NoNewline
        foreach ($mode in @('success', 'native_stdin')) {
            $env:SDLC_CAPTURE_FIXTURE = $mode
            $output = Invoke-Fixture "transport-$mode" 0
            $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
            $meta = Get-Content (Join-Path $turn 'turn.json') -Raw | ConvertFrom-Json
            $messages = @(Get-Content (Join-Path $turn 'assistant-messages.json') -Raw | ConvertFrom-Json)
            Assert ($messages[-1].content -ceq $prompt) 'Large JSON arrives unchanged through the complete launcher chain'
            Assert ($meta.command.transport -eq 'utf8-stdin-v1' -and $meta.command.inputCharacters -eq $prompt.Length) 'Transport and exact length are recorded'
            Assert ($meta.command.arguments -notcontains '-p' -and ($meta.command.arguments -join ' ').Length -lt 4096) 'Recorded process arguments contain no prompt payload'
            Assert ((Get-Content (Join-Path $turn 'input.txt') -Raw) -ceq $prompt) 'Full audit input remains intact'
            [void](Invoke-Fixture "transport-$mode" 0 -Resume)
            $turns = @(Get-ChildItem $output -Directory -Filter 'turn-*')
            Assert ($turns.Count -eq 2) 'Stdin transport supports explicit session recovery'
            foreach ($item in $turns) {
                $saved = Get-Content (Join-Path $item.FullName 'turn.json') -Raw | ConvertFrom-Json
                $reply = @(Get-Content (Join-Path $item.FullName 'assistant-messages.json') -Raw | ConvertFrom-Json)[-1].content
                Assert ($saved.sessionId -eq $meta.sessionId -and $reply -ceq $prompt) 'Resume preserves session and full input'
            }
        }
        $parseErrors = $null
        $ast = [Management.Automation.Language.Parser]::ParseFile($runner, [ref]$null, [ref]$parseErrors)
        Assert ($parseErrors.Count -eq 0) 'Collector parses'
        $definition = $ast.Find({ param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Invoke-Captured' }, $false)
        . ([scriptblock]::Create($definition.Extent.Text))
        $script:repository = $repository; $CopilotHome = $null; $script:enableFusionFeatureFlags = $false
        $nativePrefix = Join-Path $fixture.FullName 'native-direct'
        $nativeResult = Invoke-Captured (Get-Command node).Source @((Join-Path $PSScriptRoot 'fixtures/fake-stdin-native.cjs')) $nativePrefix 10 -InputText $prompt
        $nativeEvents = Get-Content "$nativePrefix.stdout" | ForEach-Object { $_ | ConvertFrom-Json }
        Assert ($nativeResult.exitCode -eq 0 -and ($nativeEvents | Where-Object type -EQ 'assistant.message').data.content -ceq $prompt) 'Direct native executables receive the same complete stdin'
        $env:SDLC_CAPTURE_FIXTURE = 'timeout'
        $clock = [Diagnostics.Stopwatch]::StartNew()
        $output = Invoke-Fixture 'transport-blocked-stdin' 124
        Assert ($clock.Elapsed.TotalSeconds -lt 20) 'A child that does not consume stdin cannot hang the collector'
        $prompt = $shortPrompt
        $prompt | Set-Content $promptFile -Encoding utf8 -NoNewline
        Write-Host 'PASS: long Unicode JSON, PowerShell/native stdin, evidence, session resume and blocked-stdin timeout'
        if ($TransportOnly) { return }
    }

    if ($PatchErrorsOnly -or -not $PSBoundParameters.Count) {
        foreach ($mode in @('patch_recovered', 'patch_unrecovered', 'patch_no_read', 'patch_other_file', 'patch_outside', 'patch_denied', 'patch_child', 'patch_no_final', 'patch_disabled')) {
            $env:SDLC_CAPTURE_FIXTURE = $mode
            $output = Invoke-Fixture $mode 0
            $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
            $runtime = Get-Content (Join-Path $turn 'runtime.json') -Raw | ConvertFrom-Json
            $recovered = $mode -eq 'patch_recovered'
            Assert ($runtime.problems.Count -eq [int](-not $recovered)) "$mode problem classification"
            Assert ($runtime.warnings.Count -eq [int]$recovered) "$mode warning classification"
            if ($recovered) {
                Assert ($runtime.warnings[0].rereadEventId -eq 'reread-ok' -and $runtime.warnings[0].recoveryEventId -eq 'patch-success' -and
                    $runtime.warnings[0].finalResponseEventId -eq 'message') 'Recovery cites reread, successful update and final response evidence.'
            }
        }
        Write-Host 'PASS: verified same-file patch recovery; unrecovered, unrelated, denied, outside, child and incomplete recovery remain fatal.'
        if ($PatchErrorsOnly) { return }
    }
    foreach ($mode in @('read_missing', 'read_denied', 'read_outside', 'read_sibling', 'read_traversal',
        'read_write', 'read_uncorrelated', 'read_unknown', 'read_no_tools', 'read_child',
        'read_range', 'read_no_final', 'read_before_error', 'read_pending_tools', 'read_blank_final', 'read_failed_exit')) {
        $env:SDLC_CAPTURE_FIXTURE = $mode
        $output = Invoke-Fixture $mode $(if ($mode -eq 'read_failed_exit') { 7 } else { 0 })
        $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
        $runtime = Get-Content (Join-Path $turn 'runtime.json') -Raw | ConvertFrom-Json
        $recoverable = $mode -in @('read_missing', 'read_range')
        Assert ($runtime.errorPolicyVersion -ceq 'local-read-errors-v2') 'Read error policy is versioned'
        Assert ($runtime.warnings.Count -eq [int]$recoverable) "$mode warning classification"
        Assert ($runtime.problems.Count -eq [int](-not $recoverable)) "$mode fatal classification"
        if ($recoverable) {
            Assert ($runtime.warnings[0].eventId -ceq 'read-failure') 'Warning preserves event provenance'
            $filename = if ($mode -eq 'read_range') { 'empty.txt' } else { 'missing.txt' }
            Assert ($runtime.warnings[0].arguments.path -ceq (Join-Path $repository $filename)) 'Warning preserves requested path'
            Assert ($runtime.warnings[0].finalResponseEventId -eq 'message' -and $runtime.warnings[0].continuationReason) 'Warning cites subsequent final response and continuation reason'
            if ($mode -eq 'read_range') { Assert ($runtime.warnings[0].arguments.view_range[1] -eq 180) 'Range evidence survives' }
        }
    }
    Write-Host 'PASS: recoverable local reads, permissions, outside paths, traversal, writes, missing correlation, unknown errors, no-tools and child calls.'
    if ($ReadErrorsOnly) { return }

    $env:SDLC_CAPTURE_FIXTURE = 'success'
    $output = Invoke-Fixture 'success' 0
    $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
    $meta = Get-Content (Join-Path $turn 'turn.json') -Raw | ConvertFrom-Json
    Assert ($meta.state -eq 'cli_exited' -and $meta.evaluation -eq 'not_scored') 'Exit is not business success'
    $messages = @(Get-Content (Join-Path $turn 'assistant-messages.json') -Raw | ConvertFrom-Json)
    Assert ($messages.Count -eq 1 -and $messages[0].content -ceq $prompt) "Prompt round-trips without shell expansion: expected=$(ConvertTo-Json -InputObject $prompt -Compress); actual=$(ConvertTo-Json -InputObject @($messages.content) -Compress)"
    $runtime = Get-Content (Join-Path $turn 'runtime.json') -Raw | ConvertFrom-Json
    Assert ($runtime.observedModels.Count -eq 0) 'Configuration changes and child calls are not root API model evidence'
    Assert ((Get-Content (Join-Path $turn 'events.stderr') -Raw) -match 'fixture stderr') 'stderr retained'
    $start = (Get-Content (Join-Path $turn 'events.stdout') -First 1) | ConvertFrom-Json
    Assert ($start.data.arguments -ccontains 'url(https://example.invalid)') 'URL colon survives PowerShell shim'
    Assert ($start.data.arguments -ccontains 'shell(git:*)') 'Tool prefix colon survives PowerShell shim'
    Assert (Test-Path (Join-Path $turn 'before\config\.github\agents\pilotRole_Product_Manager.agent.md')) 'Uncommitted agent snapshotted'
    Assert (Test-Path (Join-Path $turn 'after\workspace.json')) 'After snapshot retained'
    $session = $meta.sessionId
    [void](Invoke-Fixture 'success' 0 -Resume)
    $turns = @(Get-ChildItem $output -Directory -Filter 'turn-*')
    Assert ($turns.Count -eq 2) 'Resume appends rather than overwrites'
    foreach ($item in $turns) {
        $saved = Get-Content (Join-Path $item.FullName 'turn.json') -Raw | ConvertFrom-Json
        Assert ($saved.sessionId -eq $session) 'Resume uses explicit session ID'
    }
    [void](Invoke-Fixture 'success' 1)
    Add-Content $agentFile 'Changed contract.'
    [void](Invoke-Fixture 'success' 1 -Resume)
    $latest = Get-ChildItem $output -Directory -Filter 'turn-*' | Sort-Object Name | Select-Object -Last 1
    Assert (-not (Test-Path (Join-Path $latest.FullName 'events.stdout'))) 'Changed config blocks model invocation'

    foreach ($case in @(@('failure', 7), @('timeout', 124), @('malformed', 1), @('empty', 1))) {
        $env:SDLC_CAPTURE_FIXTURE = $case[0]
        $output = Invoke-Fixture $case[0] $case[1]
        $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
        Assert (Test-Path (Join-Path $turn 'after\workspace.json')) "$($case[0]) keeps after snapshot"
        Assert (Test-Path (Join-Path $turn 'events.stdout')) "$($case[0]) keeps raw output"
        if ($case[0] -eq 'timeout') {
            $emptyMessages = Get-Content (Join-Path $turn 'assistant-messages.json') -Raw
            Assert ($emptyMessages.Trim() -eq '[]') 'No assistant messages is serialized as a JSON array'
        }
    }
    foreach ($mode in @('modern', 'legacy', 'unknown_tool')) {
        $env:SDLC_CAPTURE_FIXTURE = $mode
        $output = Invoke-Fixture $mode 0
        $turn = @(Get-ChildItem $output -Directory -Filter 'turn-*')[0].FullName
        $runtime = Get-Content (Join-Path $turn 'runtime.json') -Raw | ConvertFrom-Json
        if ($mode -eq 'unknown_tool') {
            Assert ($runtime.problems.Count -eq 1) 'Unknown tool configuration is a runtime problem'
        }
        else {
            Assert ($runtime.observedModels.Count -eq 1 -and $runtime.observedModels[0] -ceq 'fixture-model') "$mode root API model evidence"
            Assert ($runtime.usage.Count -eq [int]($mode -eq 'legacy')) 'Missing token usage is not fabricated'
        }
    }
    Write-Host 'PASS: capture, Unicode/quoting, stderr, snapshots, resume, overwrite guard, config drift, failure, timeout, malformed, empty output, API model evidence and tool configuration.'
}
finally {
    Set-Location $originalLocation
    $env:SDLC_CAPTURE_FIXTURE = $oldMode
    Remove-Item -LiteralPath $fixture.FullName -Recurse -Force
}
